/**
 * Fails the build when a shipped map's committed `layout.ts` or `heights.ts` is
 * not what its generator writes — `npm run maps:check`, and one of
 * `npm run build`'s gates beside `check-collision.mjs`.
 *
 * **The generators are the only way to author a map** (`BABYLON_EXIT.md` X5.3,
 * row "X5.3, the generators only", the owner's of 2026-11-08). A change goes
 * into a generator's design section, its parameters or its seed, and is re-run;
 * there is no overrides file. So a committed map file that its generator no
 * longer reproduces is a hand edit nobody folded back, or a generator change
 * nobody re-ran, and either is caught here rather than discarded silently by
 * the next re-seed.
 *
 * How: each map in `collision-hash.mjs`'s `MAPS` is generated by
 * `scripts/generate-<map>.mjs --out <scratch>/<map>`, which writes there and
 * nothing in `src/`, every map in `MAPS` at once in child processes; then both
 * files are compared with `src/world/<map>/` byte for byte after LINE-ENDING
 * normalisation (CRLF to LF on both sides), because the generators write LF and
 * a Windows checkout under `core.autocrlf` holds CRLF. Nothing else is
 * normalised: one byte of any other kind fails, naming the map, the file and
 * the first line that differs.
 *
 * Invariants:
 * - It reads the committed files and writes only under the OS's temp
 *   directory, which it removes. A generator run with `--out` writes nothing in
 *   the tree.
 * - It needs no GPU, no browser and no build: the generators are plain Node
 *   (type stripping for the `.ts` modules they import).
 * - Its map list is `collision-hash.mjs`'s `MAPS`, the one table the bake and
 *   its staleness check read, so a new map is checked by the row it already
 *   owes there — and so a new map OWES a generator, `scripts/generate-<id>.mjs`
 *   taking `--out <dir>`, or its row fails the build as a generator that
 *   exited non-zero. The DEV-only proving ground (`DEV_MAPS`) is not a map
 *   anybody authors through a generator of this shape and is not checked.
 *
 * Never: write into `src/`; normalise anything but line endings; pass a map
 * whose generator exited non-zero.
 */
import { spawn } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { MAPS, root } from "./collision-hash.mjs";

const FILES = ["layout.ts", "heights.ts"];
const lf = (text) => text.replace(/\r\n/g, "\n");

/** Runs one generator into `dir`, resolving with its exit code and output. */
const generate = (id, dir) =>
  new Promise((done) => {
    const child = spawn(process.execPath, [join(root, "scripts", `generate-${id}.mjs`), "--out", dir], {
      cwd: root,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let output = "";
    child.stdout.on("data", (d) => (output += d));
    child.stderr.on("data", (d) => (output += d));
    child.on("close", (code) => done({ code, output }));
  });

/** The first line at which two texts differ, 1-based, with both lines. */
function firstDifference(want, have) {
  const a = want.split("\n");
  const b = have.split("\n");
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) return { line: i + 1, committed: a[i], generated: b[i] };
  }
  return null;
}

const scratch = mkdtempSync(join(tmpdir(), "maps-check-"));
const failures = [];
const t0 = performance.now();
try {
  const runs = await Promise.all(
    MAPS.map(async ({ id }) => ({ id, dir: join(scratch, id), ...(await generate(id, join(scratch, id))) })),
  );
  for (const { id, dir, code, output } of runs) {
    if (code !== 0) {
      failures.push(`${id}: scripts/generate-${id}.mjs exited ${code}\n${output.trim().split("\n").slice(-12).join("\n")}`);
      continue;
    }
    for (const file of FILES) {
      const committedPath = join(root, "src", "world", id, file);
      const generatedPath = join(dir, file);
      if (!existsSync(generatedPath)) {
        failures.push(`${id}/${file}: the generator wrote no such file`);
        continue;
      }
      const committed = lf(readFileSync(committedPath, "utf8"));
      const generated = lf(readFileSync(generatedPath, "utf8"));
      if (committed === generated) continue;
      const d = firstDifference(committed, generated);
      failures.push(
        `src/world/${id}/${file} differs from what scripts/generate-${id}.mjs writes, first at line ${d.line}:\n` +
          `    committed: ${d.committed === undefined ? "(end of file)" : JSON.stringify(d.committed)}\n` +
          `    generated: ${d.generated === undefined ? "(end of file)" : JSON.stringify(d.generated)}`,
      );
    }
  }
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

const secs = ((performance.now() - t0) / 1000).toFixed(1);
if (failures.length > 0) {
  console.error("\nA map does not reproduce from its generator:\n");
  for (const f of failures) console.error(`  ${f}\n`);
  console.error(
    "A map is authored in its generator only (BABYLON_EXIT.md X5.3). Fold the change into\n" +
      "scripts/generate-<map>.mjs and re-run it (`npm run <map>`), then `npm run collision -- <map>`\n" +
      "and `npm run parity`.\n",
  );
  process.exit(1);
}
console.log(`maps reproduce from their generators: ${MAPS.map((m) => m.id).join(", ")} (${secs} s)`);

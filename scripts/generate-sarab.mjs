// passes at full precision and fails at two decimals is a map that fails.
const q = new Float64Array(row * row);
for (let k = 0; k < q.length; k++) q[k] = Math.round(heights[k] * 100) / 100;

let worstStep = 0;
let worstAt = "";
for (let j = 0; j < row; j++) {
  for (let i = 0; i < row; i++) {
    const h = q[j * row + i];
    if (i + 1 < row) {
      const s = Math.abs(q[j * row + i + 1] - h);
      if (s > worstStep) {
        worstStep = s;
        worstAt = `(${-HALF + i * CELL}, ${-HALF + j * CELL}) along X`;
      }
    }
    if (j + 1 < row) {
      const s = Math.abs(q[(j + 1) * row + i] - h);
      if (s > worstStep) {
        worstStep = s;
        worstAt = `(${-HALF + i * CELL}, ${-HALF + j * CELL}) along Z`;
      }
    }
  }
}

/**
 * generate-sarab.mjs — SEEDS Sarab, the desert town: writes
 * `src/world/sarab/{layout,heights}.ts`.
 *
 * Run with `npm run sarab`. Committed output, like every `heights.ts` and every
 * collision bake, and re-running it with the tree unchanged must produce the
 * same bytes.
 *
 * `--out <dir>` (or `--out=<dir>`) writes the two files into `<dir>` and
 * nothing in `src/`, and an `--out` naming no directory is refused: how
 * `npm run maps:check` (`scripts/check-maps.mjs`, a build gate) re-runs this
 * and holds the committed files to those bytes.
 *
 * ## Why this map is seeded by a script and the other four are not
 *
 * Two reasons, and only the second is about this map in particular.
 *
 * **The floor.** A `Heightfield` at this extent is 226 x 226 vertices — fifty
 * thousand numbers, which is a hundred times what a hand can hold and four
 * times what the map editor's terrain brush was a reasonable way to paint. Every map
 * in the tree has a generated `heights.ts` for exactly this reason; the other
 * four were generated by the editor and this one is generated here, because a
 * wadi that meanders across 1.5 km of ground is a FUNCTION and painting it by
 * hand would be transcribing one.
 *
 * **The extent.** Sarab's play square is 900 m — 5.1 times Harrowmead's area —
 * and a town that fills it is some hundreds of buildings. Coldharbour is 500
 * placements over 320 m and was authored line by line; the same density here is
 * several thousand lines whose only content is that nothing overlaps anything.
 * So the DESIGN is authored — the flags, the quarters, the street pitch, the
 * recipes each quarter's blocks are drawn from, every set piece — and the
 * TRANSCRIPTION is mechanical.
 *
 * **The output is still the map, and this script is its only author.**
 * `src/world/sarab/layout.ts` is a normal layout file, and a change to it goes
 * into this script and is re-run. The build does not generate it — it runs
 * this script into scratch and fails on a byte the committed file differs by
 * (`npm run maps:check`, `scripts/check-maps.mjs`).
 *
 * ## The town, and what each part of it is for
 *
 * See the header this writes into `layout.ts` — it carries the map's own
 * argument, and repeating it here would give it two places to be wrong.
 *
 * What lives HERE rather than there is the construction:
 *
 * - **The floor is dunes, flattened under the districts, then cut by the
 *   wadi.** A placement's height is sampled ONCE at its own centre, so a
 *   building on a grade floats at one corner and buries itself at the other;
 *   `DISTRICTS` is the list of places that therefore have to be dead flat, and
 *   the skirt between two of them at different levels is what makes the
 *   Martyrs' Quarter stand seven metres over the town rather than balance on a
 *   cliff. Every gradient this produces is checked against
 *   `MAX_WALKABLE_GRADE` before the file is written, and the script REFUSES to
 *   write one it cannot walk.
 * - **Nothing overlaps anything, and that is enforced rather than authored.**
 *   Every placement, road, flag ring, spawn and hardstanding claims an
 *   axis-aligned rectangle, and a candidate that would land on a claimed one is
 *   dropped. So a quarter's recipe can ask for more than fits and get what
 *   fits, which is what makes the fabric read as a town that grew rather than
 *   as a grid that was filled.
 * - **The stream is one, in authored order.** `MapBuilder.scatterRegion` draws
 *   every region from one seeded stream in array order, so this script emits
 *   the scatter array in a fixed order and a region added in the middle of it
 *   re-rolls every field below — the same rule Harrowmead's layout states, and
 *   the reason the two blocks at the end of that array are appended.
 */
